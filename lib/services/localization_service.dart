enum AppLanguage {
  tr('Türkçe', 'Turkish', 'tr', '🇹🇷'),
  en('English', 'English', 'en', '🇬🇧'),
  fr('Français', 'French', 'fr', '🇫🇷'),
  de('Deutsch', 'German', 'de', '🇩🇪'),
  it('Italiano', 'Italian', 'it', '🇮🇹'),
  ar('العربية', 'Arabic', 'ar', '🇸🇦'),
  da('Dansk', 'Danish', 'da', '🇩🇰');

  final String nativeName;
  final String englishName;
  final String code;
  final String flag;

  const AppLanguage(this.nativeName, this.englishName, this.code, this.flag);

  bool get isRTL => this == AppLanguage.ar;
}

class AppLocale extends ChangeNotifier {
  static const String _prefKey = 'selected_language';
  AppLanguage _current = AppLanguage.tr;

  AppLanguage get current => _current;
  bool get isRTL => _current.isRTL;
  TextDirection get textDirection => _current.isRTL ? TextDirection.rtl : TextDirection.ltr;
  Locale get locale => Locale(_current.code);

  AppLocale() {
    _loadFromPrefs();
  }

  Future<void> _loadFromPrefs() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final code = prefs.getString(_prefKey);
      if (code != null) {
        final found = AppLanguage.values.firstWhere(
          (l) => l.code == code,
          orElse: () => AppLanguage.tr,
        );
        _current = found;
        notifyListeners();
      }
    } catch (_) {}
  }

  Future<void> setLanguage(AppLanguage language) async {
    if (_current == language) return;
    _current = language;
    notifyListeners();
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, language.code);
    } catch (_) {}
  }

  String t(String key, [Map<String, String>? params]) {
    String text = _translations[_current]?[key] ?? _translations[AppLanguage.en]?[key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        text = text.replaceAll('{$k}', v);
      });
    }
    return text;
  }

